"""SYNTHETIC feature data for software testing and demos ONLY.

Every row has source='synthetic' and is_synthetic=True; IDs are prefixed 'SYN_'.
The label-dependent shifts below are arbitrary and exist only so that the training code
has something to fit. Results on this data say nothing about real behaviour.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from src.data.feature_schema import ALL_COLUMNS, empty_row

SYNTHETIC_NOTICE = ("SYNTHETIC DATA - generated by src/data/synthetic.py for software testing. "
                    "Not real participants. Never use for research claims.")


def generate_synthetic_features(n_participants: int = 12, videos_per_participant: int = 3,
                                seconds: float = 12.0, fps: float = 5.0, seed: int = 42,
                                missing_rate: float = 0.05) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    pids = [f"SYN_P{i:02d}" for i in range(1, n_participants + 1)]
    n_test = max(1, n_participants // 6)
    n_val = max(1, n_participants // 6)
    split_of = {p: ("test" if i < n_test else "validation" if i < n_test + n_val else "train")
                for i, p in enumerate(pids)}
    rows = []
    n_frames = int(seconds * fps)
    for p in pids:
        for v in range(1, videos_per_participant + 1):
            vid = f"{p}_V{v:02d}"
            eng = int(rng.integers(0, 4))
            other = {k: int(rng.integers(0, 4)) for k in ("boredom", "confusion", "frustration")}
            shift = (eng - 1.5) / 1.5          # arbitrary signal, -1..1
            blink_count = 0
            for f in range(n_frames):
                t = f / fps
                r = empty_row()
                r.update(participant_id=p, video_id=vid, frame_index=f, timestamp_s=round(t, 3),
                         source="synthetic", is_synthetic=True, split=split_of[p],
                         label_policy="broadcast_video_label", label_engagement=eng,
                         label_boredom=other["boredom"], label_confusion=other["confusion"],
                         label_frustration=other["frustration"])
                missing = rng.random() < missing_rate
                multi = (not missing) and rng.random() < 0.01
                if missing:
                    r.update(face_detected=False, num_faces=0, brightness=float(rng.uniform(20, 60)),
                             low_light=True, quality_ok=False)
                else:
                    blink = rng.random() < 0.06
                    blink_count += int(blink)
                    ear = float(np.clip(rng.normal(0.29 + 0.01 * shift, 0.02) - (0.15 if blink else 0), 0.05, 0.45))
                    r.update(ear_left=ear + rng.normal(0, 0.005), ear_right=ear + rng.normal(0, 0.005), ear_mean=ear,
                             blink_event=float(blink),
                             blink_rate_per_min=(60.0 * blink_count / t) if t >= 10 else np.nan,
                             gaze_h=float(rng.normal(0, 0.15 + 0.15 * max(0, -shift))),
                             gaze_v=float(rng.normal(0.05 * -shift, 0.15)),
                             head_yaw=float(rng.normal(0, 5 + 8 * max(0, -shift))),
                             head_pitch=float(rng.normal(5 * -shift, 4)), head_roll=float(rng.normal(0, 3)),
                             mouth_aspect_ratio=float(abs(rng.normal(0.08, 0.04))),
                             brow_raise=float(rng.normal(0.08, 0.01)), face_scale=float(rng.normal(0.45, 0.03)),
                             face_center_x=float(rng.normal(0.5, 0.03)), face_center_y=float(rng.normal(0.5, 0.03)),
                             face_detected=True, num_faces=2 if multi else 1, multiple_faces=multi,
                             brightness=float(rng.uniform(90, 160)), landmarks_complete=True,
                             quality_ok=not multi)
                rows.append(r)
    return pd.DataFrame(rows, columns=ALL_COLUMNS)


def write_synthetic(df: pd.DataFrame, demo_dir: Path) -> Path:
    demo_dir.mkdir(parents=True, exist_ok=True)
    path = demo_dir / "synthetic_features.csv"
    df.to_csv(path, index=False)
    (demo_dir / "SYNTHETIC_DATA_NOTICE.txt").write_text(SYNTHETIC_NOTICE + "\n", encoding="utf-8")
    return path
